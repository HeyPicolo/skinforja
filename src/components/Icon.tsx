export function Icon({ name, size = 18 }: { name: keyof typeof ICONS | string; size?: number }) {
  const rows = ICONS[name];
  if (!rows) return null;
  const rects: JSX.Element[] = [];
  rows.forEach((row, y) => {
    let start = -1;
    for (let x = 0; x <= row.length; x++) {
      const on = row[x] === '#';
      if (on && start < 0) start = x;
      if (!on && start >= 0) { rects.push(<rect key={`${y}-${start}`} x={start} y={y} width={x - start} height={1} />); start = -1; }
    }
  });
  return (
    <svg className="icon" width={size} height={size} viewBox="0 0 12 12" fill="currentColor" aria-hidden="true" shapeRendering="crispEdges">
      {rects}
    </svg>
  );
}
