export type KidIconName = keyof typeof ICONS;

export function KidIcon({ name, size = 40, color }: { name: string; size?: number; color?: string }) {
  const def = ICONS[name];
  if (!def) return null;
  const rects: JSX.Element[] = [];
  def.rows.forEach((row, y) => {
    let x = 0;
    while (x < row.length) {
      const ch = row[x];
      if (ch === '.') { x++; continue; }
      let end = x + 1;
      while (end < row.length && row[end] === ch) end++;
      let fill = def.legend[ch] ?? K;
      if (fill === 'C') fill = color ?? '#e5484d';
      rects.push(<rect key={`${y}-${x}`} x={x} y={y} width={end - x} height={1} fill={fill} />);
      x = end;
    }
  });
  return (
    <svg className="kicon" width={size} height={size} viewBox="0 0 12 12" aria-hidden="true" shapeRendering="crispEdges">
      {rects}
    </svg>
  );
}
